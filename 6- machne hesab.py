num1 = float(input('number1: '))
operation = input('operation: ')
num2 = float(input('number2: '))

if operation =='+':
    print(num1 + num2 )
elif operation =='-':
    print(num1 - num2 )
elif operation =='*':
    print(num1 * num2 )
elif operation == '/':
    print(num1 / num2)



